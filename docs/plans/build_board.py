"""Validate board.json and render board.html (the Development Board artifact).

Run: python docs/plans/build_board.py
Fails loudly on: unknown dependency, dependency cycle, bad status or phase, duplicate id.
Also reads the memory graph in docs/memory/*.md (see docs/memory/memory-system.md),
fails on a broken [[link]] or a bad note, and writes docs/memory/INDEX.md.
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
board = json.load(open(os.path.join(HERE, 'board.json'), encoding='utf-8'))
tasks = board['tasks']
ids = [t['id'] for t in tasks]
byid = {t['id']: t for t in tasks}
phases = {p['id'] for p in board['phases']}
errors = []
if len(ids) != len(set(ids)):
    errors.append('duplicate task id')
for t in tasks:
    if t['status'] not in board['status_values']:
        errors.append(f"{t['id']}: bad status {t['status']}")
    if t['phase'] not in phases:
        errors.append(f"{t['id']}: bad phase {t['phase']}")
    for d in t['deps']:
        if d not in byid:
            errors.append(f"{t['id']}: unknown dependency {d}")
    if t['status'] == 'done' and not t.get('done_on'):
        errors.append(f"{t['id']}: done without done_on")

# cycle check (depth-first search)
state = {}
def visit(n, path):
    if state.get(n) == 1:
        errors.append('dependency cycle: ' + ' -> '.join(path + [n]))
        return
    if state.get(n) == 2:
        return
    state[n] = 1
    for d in byid[n]['deps']:
        if d in byid:
            visit(d, path + [n])
    state[n] = 2
for n in ids:
    visit(n, [])
if errors:
    sys.exit('board.json invalid:\n  ' + '\n  '.join(errors))

for t in tasks:
    t['ready'] = t['status'] == 'todo' and all(byid[d]['status'] == 'done' for d in t['deps'])

# memory graph: one note per file, YAML-ish frontmatter, [[slug]] links to notes or task ids
MEM = os.path.join(HERE, '..', 'memory')
TYPES = ['area', 'decision', 'constraint', 'lesson', 'environment', 'session']
def parse(text):
    m = re.match(r'---\n(.*?)\n---\n(.*)', text.replace('\r', ''), re.S)
    if not m:
        return None, text
    meta = dict(l.split(':', 1) for l in m.group(1).splitlines() if ':' in l)
    return {k.strip(): v.strip().strip('"') for k, v in meta.items()}, m.group(2).strip()
assert parse('---\nname: a\ntype: area\n---\nhi [[b]]')[0] == {'name': 'a', 'type': 'area'}
notes = []
for f in sorted(os.listdir(MEM)):
    if not f.endswith('.md') or f == 'INDEX.md':
        continue
    meta, body = parse(open(os.path.join(MEM, f), encoding='utf-8').read())
    if not meta or meta.get('name') != f[:-3]:
        errors.append(f'memory/{f}: frontmatter missing or name does not match the file name')
        continue
    if meta.get('type') not in TYPES:
        errors.append(f'memory/{f}: type must be one of {TYPES}')
    if not meta.get('description') or not meta.get('updated'):
        errors.append(f'memory/{f}: needs description and updated')
    notes.append({'id': meta['name'], 'type': meta.get('type'), 'description': meta.get('description', ''),
                  'updated': meta.get('updated', ''), 'body': body,
                  'links': sorted(set(re.findall(r'\[\[([^\]|]+)\]\]', re.sub(r'`[^`]*`', '', body))))})
note_ids = {n['id'] for n in notes}
for n in notes:
    for l in n['links']:
        if l not in note_ids and l not in byid:
            errors.append(f"memory/{n['id']}.md: broken link [[{l}]]")
linked = {l for n in notes for l in n['links']}
for n in notes:
    if not n['links'] and n['id'] not in linked:
        errors.append(f"memory/{n['id']}.md: orphan note, link it from an area note")
if errors:
    sys.exit('board or memory invalid:\n  ' + '\n  '.join(errors))
board['memory'] = notes
idx = ['# Memory index', '', 'Generated by `python docs/plans/build_board.py`. Do not edit by hand.', '']
for t in TYPES:
    group = sorted((n for n in notes if n['type'] == t), key=lambda n: n['id'])
    if group:
        idx += [f'## {t.capitalize()}'] + [f"- [{n['id']}]({n['id']}.md): {n['description']}" for n in group] + ['']
open(os.path.join(MEM, 'INDEX.md'), 'w', encoding='utf-8', newline='\n').write('\n'.join(idx))

data = json.dumps(board, ensure_ascii=False).replace('</', '<\\/')
done = sum(t['status'] == 'done' for t in tasks)
html = open(os.path.join(HERE, 'board_template.html'), encoding='utf-8').read()
html = html.replace('/*__DATA__*/null', data)
open(os.path.join(HERE, 'board.html'), 'w', encoding='utf-8', newline='\n').write(html)
ready = [t['id'] for t in tasks if t['ready']]
print(f"{len(tasks)} tasks · {done} done · {len(notes)} memory notes · ready now: {', '.join(ready) or 'none'}")
